/**
 * Next.js公式のinstrumentationフック。サーバーインスタンス起動時に一度だけ、
 * リクエスト処理が始まる前に実行される（Node.jsランタイムのみ。詳細は
 * https://nextjs.org/docs/app/api-reference/file-conventions/instrumentation を参照）。
 *
 * ここでは日時まわりの本番バグ修正のため、TZ環境変数を明示的に日本時間へ固定する。
 *
 * --- 背景 ---
 * このアプリの日時処理（dateKey.ts・getFloorMapData.ts・予約フォームのdatetime-local
 * パース・timelineLayout.ts等）は、「サーバーのローカル時刻をそのままその組織の
 * 営業日・営業時刻とみなす」設計にしている（1組織＝1タイムゾーンという前提の
 * シンプルな実装。詳細はdateKey.ts冒頭のコメントを参照）。
 *
 * この前提は、ローカル開発機のOSが日本時間に設定されている間は問題なく成立するが、
 * 本番のVercel（Node.jsのデフォルトはTZ=UTC）ではサーバーのローカル時刻がUTCになる
 * ため、例えば予約フォームで「10:00」と入力しても、`new Date("...T10:00")`が
 * UTCの10:00（＝日本時間19:00）として解釈されてしまい、9時間ずれて登録される
 * 不具合が発生していた（逆に読み出し側も同じズレ方をするため、アプリの画面内だけ
 * 見ている分には気づきにくく、実際の時刻（「使用中」判定や外部から見た予約時刻）と
 * 比べて初めて表面化する）。
 *
 * サーバー起動時にTZを明示的に固定することで、日時処理まわりの既存コードを一切
 * 変更せずに、ローカル・本番のどちらでも「サーバーのローカル時刻＝日本時間」という
 * 前提を確実に成立させる（同時に、ローカル開発時の挙動が開発者のOS設定に
 * 依存しなくなるという副次的な利点もある）。
 */
export function register() {
  process.env.TZ = "Asia/Tokyo";
}
